import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const files = [
  ...['src/sim', 'src/data', 'src/ai'].flatMap((dir) =>
    readdirSync(dir).filter((file) => file.endsWith('.ts')).map((file) => dir + '/' + file)),
  'src/modes/gacha.ts', 'src/net/roomSim.ts', 'src/net/roomState.ts', 'src/net/roomWire.ts', 'src/net/pvpModes.ts',
].sort();
const hash = createHash('sha256');
for (const file of files) hash.update(file).update('\0').update(readFileSync(file)).update('\0');
const generated = `// Generated by npm run pvp:version.\nexport const ROOM_RULES = '${hash.digest('hex').slice(0, 24)}';\n`;
const path = 'src/net/roomVersion.ts';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== generated) {
    console.error('Room simulation version is stale. Run npm run pvp:version and commit the result.');
    process.exitCode = 1;
  }
} else writeFileSync(path, generated);
